/// root
///   api
///     routes
///       endpoint (out: req, in: res)
///   jwt (in: validate, out: result)
///   p1 / a (out: o)
///   p2 / b (in: i)
fn fixture() -> Document {
    Builder::new()
        .module("api")
        .module_in("routes", "api")
        .named_module("endpoint", "routes", "Protected Endpoint")
        .named_output("endpoint", "req", "Token Check")
        .named_input("endpoint", "res", "Token Verdict")
        .named_module("jwt", "root", "JWT Validator")
        .named_input("jwt", "validate", "Validate Token")
        .named_output("jwt", "result", "Validation Result")
        .module("p1")
        .module_in("a", "p1")
        .output("a", "o")
        .module("p2")
        .module_in("b", "p2")
        .input("b", "i")
        .doc
}

fn kinds(steps: &[RouteStep]) -> Vec<&'static str> {
    steps
        .iter()
        .map(|s| match s {
            RouteStep::CreatePort { .. } => "create-port",
            RouteStep::ReusePort { .. } => "reuse-port",
            RouteStep::CreateConnection { .. } => "create-connection",
            RouteStep::ReuseConnection { .. } => "reuse-connection",
        })
        .collect()
}

fn route(doc: &Document, from: &str, to: &str, gen: &mut SequentialIdGenerator) -> Result<RouteResult> {
    route_connection(doc, &ep(from), &ep(to), RouteOptions { id_generator: Some(gen), ..Default::default() })
}

/// No stored connection may reference anything but the container or its direct children.
fn assert_only_local(doc: &Document) {
    assert_eq!(validate_document(doc, ValidationOptions { warnings: false }).errors, vec![]);
}

fn created_ports(steps: &[RouteStep]) -> Vec<(String, PortDirection)> {
    steps
        .iter()
        .filter_map(|s| match s {
            RouteStep::CreatePort { module_id, direction, .. } => Some((module_id.clone(), *direction)),
            _ => None,
        })
        .collect()
}

#[test]
fn connects_siblings_directly() {
    let doc = Builder::new().module("a").module("b").output("a", "o").input("b", "i").doc;
    let r = route(&doc, "a:o", "b:i", &mut SequentialIdGenerator::default()).unwrap();
    assert_eq!(kinds(&r.plan.steps), vec!["create-connection"]);
    assert_eq!(r.plan.lowest_common_ancestor_id, "root");
    assert_eq!(module(&r.document, "root").connections.len(), 1);
}

#[test]
fn connects_cousins_through_both_parents() {
    let r = route(&fixture(), "a:o", "b:i", &mut SequentialIdGenerator::default()).unwrap();
    assert_eq!(
        kinds(&r.plan.steps),
        vec!["create-port", "create-connection", "create-port", "create-connection", "create-connection"]
    );
    assert_eq!(module(&r.document, "p1").outputs.iter().map(|p| p.name.as_str()).collect::<Vec<_>>(), vec!["o"]);
    assert_eq!(module(&r.document, "p2").inputs.iter().map(|p| p.name.as_str()).collect::<Vec<_>>(), vec!["i"]);
    assert_only_local(&r.document);
}

#[test]
fn routes_from_a_deep_module_up_to_a_root_level_module() {
    let r = route(&fixture(), "endpoint:req", "jwt:validate", &mut SequentialIdGenerator::default()).unwrap();
    assert_eq!(r.plan.lowest_common_ancestor_id, "root");
    let created: Vec<String> = created_ports(&r.plan.steps).into_iter().map(|(m, _)| m).collect();
    assert_eq!(created, vec!["routes", "api"]);
    let port = &module(&r.document, "routes").outputs[0];
    assert_eq!((port.id.as_str(), port.name.as_str()), ("port-1", "Token Check"));
    assert!(port.description.contains("Generated by boundary routing"));
    let conn = |id: &str, from: &str, to: &str| Connection { id: id.into(), from: ep(from), to: ep(to) };
    assert_eq!(module(&r.document, "routes").connections, vec![conn("conn-1", "endpoint:req", "routes:port-1")]);
    assert_eq!(module(&r.document, "api").connections, vec![conn("conn-2", "routes:port-1", "api:port-2")]);
    assert_eq!(module(&r.document, "root").connections, vec![conn("conn-3", "api:port-2", "jwt:validate")]);
    assert_only_local(&r.document);
}

#[test]
fn routes_down_into_deep_descendants() {
    let r = route(&fixture(), "jwt:result", "endpoint:res", &mut SequentialIdGenerator::default()).unwrap();
    assert_eq!(
        created_ports(&r.plan.steps),
        vec![("api".to_string(), PortDirection::Input), ("routes".to_string(), PortDirection::Input)]
    );
    assert_eq!(module(&r.document, "api").inputs[0].name, "Token Verdict");
    assert_only_local(&r.document);
}

#[test]
fn routes_from_a_parent_input_into_a_nested_descendant() {
    let doc = Builder::new()
        .module("outer")
        .input("outer", "in")
        .module_in("mid", "outer")
        .module_in("leaf", "mid")
        .input("leaf", "x")
        .doc;
    let r = route(&doc, "outer:in", "leaf:x", &mut SequentialIdGenerator::default()).unwrap();
    assert_eq!(r.plan.lowest_common_ancestor_id, "outer");
    assert_eq!(module(&r.document, "outer").connections[0].from, ep("outer:in"));
    assert_only_local(&r.document);
}

#[test]
fn reuses_existing_boundary_ports_when_unambiguous_never_by_name() {
    let first = route(&fixture(), "endpoint:req", "jwt:validate", &mut SequentialIdGenerator::new("a-")).unwrap();
    // Same route again: everything is reused, nothing is created.
    let again = route(&first.document, "endpoint:req", "jwt:validate", &mut SequentialIdGenerator::new("b-")).unwrap();
    assert_eq!(
        kinds(&again.plan.steps),
        vec!["reuse-port", "reuse-connection", "reuse-port", "reuse-connection", "reuse-connection"]
    );
    assert_eq!(again.document, first.document);

    // reuse: false creates fresh ports.
    let mut gen = SequentialIdGenerator::new("c-");
    let fresh = route_connection(
        &first.document,
        &ep("endpoint:req"),
        &ep("jwt:validate"),
        RouteOptions { id_generator: Some(&mut gen), reuse: false, ..Default::default() },
    )
    .unwrap();
    assert_eq!(module(&fresh.document, "routes").outputs.len(), 2);
}

#[test]
fn uses_explicitly_identified_ports_via_via() {
    let doc = Builder::new()
        .module("api")
        .module_in("routes", "api")
        .module_in("endpoint", "routes")
        .output("endpoint", "req")
        .named_output("routes", "existing", "Existing Out")
        .module("jwt")
        .input("jwt", "validate")
        .doc;
    let mut gen = SequentialIdGenerator::default();
    let via: JsMap<String> = [("routes", "existing".to_string())].into_iter().collect();
    let r = route_connection(
        &doc,
        &ep("endpoint:req"),
        &ep("jwt:validate"),
        RouteOptions { id_generator: Some(&mut gen), via, ..Default::default() },
    )
    .unwrap();
    assert_eq!(
        r.plan.steps[0],
        RouteStep::ReusePort {
            module_id: "routes".into(),
            direction: PortDirection::Output,
            port_id: "existing".into()
        }
    );
    assert_eq!(
        js::stringify(&js::to_value(&r.plan.steps[0])),
        r#"{"kind":"reuse-port","moduleId":"routes","direction":"output","portId":"existing"}"#
    );
    assert_eq!(module(&r.document, "routes").outputs.len(), 1);
    assert_only_local(&r.document);
}

#[test]
fn never_merges_ports_whose_names_collide() {
    let doc = Builder::new()
        .module("api")
        .module_in("routes", "api")
        .module_in("endpoint", "routes")
        .named_output("endpoint", "req", "Token Check")
        .named_output("routes", "unrelated", "Token Check")
        .module("jwt")
        .input("jwt", "validate")
        .doc;
    let r = route(&doc, "endpoint:req", "jwt:validate", &mut SequentialIdGenerator::default()).unwrap();
    let outputs = &module(&r.document, "routes").outputs;
    assert_eq!(outputs.iter().map(|p| p.name.as_str()).collect::<Vec<_>>(), vec!["Token Check", "Token Check"]);
    assert_eq!(outputs.iter().map(|p| p.id.as_str()).collect::<Vec<_>>(), vec!["unrelated", "port-1"]);
}

#[test]
fn rolls_back_atomically_when_a_later_step_fails() {
    let doc = fixture();
    let snapshot = doc.clone();
    // The second generated port ID collides with an existing port on "api".
    let doc = Builder { doc }.output("api", "dup").doc;
    let before = doc.clone();
    let mut n = 0;
    let mut gen = |kind: IdKind| {
        if kind == IdKind::Port {
            n += 1;
            if n == 1 {
                "fresh".to_string()
            } else {
                "dup".to_string()
            }
        } else {
            format!("c{n}")
        }
    };
    let r = route_connection(
        &doc,
        &ep("endpoint:req"),
        &ep("jwt:validate"),
        RouteOptions { id_generator: Some(&mut gen), ..Default::default() },
    );
    assert_eq!(r.unwrap_err().code, ErrorCode::InvalidArgument);
    assert_eq!(doc, before);
    assert_ne!(doc, snapshot);
}

#[test]
fn rejects_invalid_destinations_and_via_entries() {
    let doc = fixture();
    let plain = |from: &str, to: &str| route_connection(&doc, &ep(from), &ep(to), RouteOptions::default());
    assert_eq!(plain("endpoint:req", "jwt:missing").unwrap_err().code, ErrorCode::NotFound);
    assert_eq!(plain("endpoint:req", "nope:x").unwrap_err().code, ErrorCode::NotFound);
    let via = |doc: &Document, module: &str, port: &str| {
        let via: JsMap<String> = [(module, port.to_string())].into_iter().collect();
        route_connection(doc, &ep("endpoint:req"), &ep("jwt:validate"), RouteOptions { via, ..Default::default() })
    };
    assert!(via(&doc, "p1", "x").unwrap_err().message.contains("not on the route"));
    let doc = Builder { doc }.input("routes", "wrong-direction").doc;
    assert!(via(&doc, "routes", "wrong-direction").unwrap_err().message.contains("needs an output"));
}
